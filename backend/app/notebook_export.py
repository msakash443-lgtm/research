"""Reproducible-notebook export for one stored `AnalysisRun` (M5.4.2, spec 5.9 bullet 4).

Pure: builds a minimal nbformat-4 notebook (markdown + code cells) from already-stored, already-visible data (the
locked plan's generated script, the dataset content at the same visibility as `GET .../datasets/{id}/content`, and
the run's recorded output). Nothing here executes the notebook or calls Docker; the notebook documents how to
re-run the exact script locally and shows what was recorded when the platform ran it.
"""

from __future__ import annotations

import json
from typing import Any


def _markdown(*lines: str) -> dict[str, Any]:
    return {"cell_type": "markdown", "metadata": {}, "source": [line + "\n" for line in lines]}


def _code(*lines: str) -> dict[str, Any]:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": [line + "\n" for line in lines]}


def build_notebook(
    *,
    plan_id: str,
    run_id: str,
    dataset_name: str,
    dataset_csv: str,
    plan_sha256: str,
    dataset_sha256: str,
    environment_sha256: str,
    image: str,
    script: str,
    output: dict[str, Any],
    output_sha256: str,
    run_created_at: str,
) -> dict[str, Any]:
    """Return an nbformat-4 notebook dict, ready to serialise with `json.dumps`."""
    provenance = _markdown(
        f"# Reproducible analysis notebook",
        "",
        f"- Analysis plan: `{plan_id}`",
        f"- Run: `{run_id}`, recorded at {run_created_at}",
        f"- Dataset: {dataset_name!r}, SHA-256 `{dataset_sha256}`",
        f"- Plan hash: `{plan_sha256}`",
        f"- Pinned environment hash: `{environment_sha256}`",
        f"- Sandbox image: `{image}`",
        f"- Recorded output SHA-256: `{output_sha256}`",
        "",
        "The script below is standard library only and refuses to run over a dataset whose SHA-256 does not "
        "match the one above. Run the next two cells in order to reproduce the recorded output exactly.",
    )
    dataset_cell = _code(
        "# Write the exact dataset this plan was locked on to a local file.",
        f"DATASET_CSV = {dataset_csv!r}",
        "with open('dataset.csv', 'w', newline='') as handle:",
        "    handle.write(DATASET_CSV)",
    )
    script_cell = _code(
        "# The exact locked analysis script (generated by app/analysis_plan.py::generate_script).",
        "ANALYSIS_SCRIPT = " + repr(script),
        "with open('analysis.py', 'w') as handle:",
        "    handle.write(ANALYSIS_SCRIPT)",
        "",
        "import subprocess, sys",
        "result = subprocess.run([sys.executable, '-I', 'analysis.py', 'dataset.csv'], capture_output=True, text=True)",
        "print(result.stdout or result.stderr)",
    )
    recorded_cell = _markdown(
        "## Output recorded when the platform ran this (for comparison)",
        "",
        "```json",
        json.dumps(output, sort_keys=True, indent=2),
        "```",
    )
    return {
        "cells": [provenance, dataset_cell, script_cell, recorded_cell],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
