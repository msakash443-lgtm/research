"""Manuscript export (X.31.13, M6.5): the saved sections as Markdown, DOCX, LaTeX or JSON, pure functions with no
database access.

A section is the ProseMirror JSON of its latest saved version (schema in `app/ledger.py`). Exports carry the researcher's
text and citations only; authorship marks (`prov`) are the provenance report's job and are left out. A citation (`cite`
node) is shown using the project's citation style (`app.csl_styles`, M6.5) when its source is verified; an unverified or
missing source shows a plain marker and is never listed in the references (plan rule 24). An inserted number (`stat`
node, M6.3) is shown as the exact value at its `path` in the named `AnalysisRun`'s stored output; one that cannot be
resolved shows a plain marker instead of a guess (`M6.4`-style export blocking already refuses these before rendering
is reached in the live export route). Submission statements (data availability, conflict of interest, ethics — M6.5)
are the researcher's own words, carried verbatim; an unset one shows a bracketed to-complete marker, the same
convention `app.ethics_pack` uses, and is never invented.
"""

from __future__ import annotations

import io
import json
from dataclasses import dataclass
from typing import Any, Iterator

from docx import Document as WordDocument
from docx.text.paragraph import Paragraph

from app import csl_styles, number_citation

UNVERIFIED_LABEL = "[unverified source]"
UNKNOWN_LABEL = "[unknown source]"
UNVERIFIED_NUMBER_LABEL = "[unverified number]"
REFERENCES_TITLE = "References"
STATEMENTS_TITLE = "Statements"
CREDIT_TITLE = "Author Contributions (CRediT)"
STATEMENT_FILL = "[{}: to complete]"
NO_CONTRIBUTORS = "No CRediT contribution roles have been assigned to this project's members yet."
# (Statements field name, display label), in the order they are rendered.
STATEMENT_FIELDS: tuple[tuple[str, str], ...] = (
    ("data_availability", "Data Availability Statement"),
    ("conflict_of_interest", "Conflict of Interest Statement"),
    ("ethics", "Ethics Statement"),
    ("ai_use_disclosure", "AI-Use Disclosure"),
)


@dataclass(frozen=True)
class CitedSource:
    """A project source as export needs it. `verified` False means it is cited but must not be listed or exported."""

    id: str
    title: str
    authors: tuple[str, ...]
    year: int | None
    venue: str | None
    doi: str | None
    verified: bool


@dataclass(frozen=True)
class Section:
    title: str
    content: dict[str, Any]


@dataclass(frozen=True)
class Statements:
    """The researcher's own submission-statement text (M6.5), plus the generated AI-use disclosure and CRediT
    author contributions (M6.6). `None`/empty means not yet written or assigned; `ai_use_disclosure` is always
    generated by `app.ai_disclosure.generate`, never researcher-written, so it is never left blank by the
    researcher (an empty string only happens if a caller skips generating it, and still shows the "to
    complete" fallback rather than silently omitting the statement)."""

    data_availability: str | None = None
    conflict_of_interest: str | None = None
    ethics: str | None = None
    ai_use_disclosure: str | None = None
    # (contributor name, CRediT roles) pairs, in the order the project lists its members. A human only -
    # AI is never a project member, so it can never appear here.
    credit: tuple[tuple[str, tuple[str, ...]], ...] = ()


def cited_source_ids(content: dict[str, Any]) -> list[str]:
    """Source ids cited in a document, in order of first use."""
    seen: dict[str, None] = {}
    for node in _walk(content):
        if node.get("type") == "cite":
            source_id = (node.get("attrs") or {}).get("source_id")
            if source_id:
                seen.setdefault(source_id, None)
    return list(seen)


def stat_run_ids(content: dict[str, Any]) -> list[str]:
    """Analysis-run ids an inserted number refers to in a document, in order of first use."""
    seen: dict[str, None] = {}
    for node in _walk(content):
        if node.get("type") == "stat":
            run_id = (node.get("attrs") or {}).get("analysis_run_id")
            if run_id:
                seen.setdefault(run_id, None)
    return list(seen)


def citation_label(source: CitedSource | None) -> str:
    if source is None:
        return UNKNOWN_LABEL
    if not source.verified:
        return UNVERIFIED_LABEL
    return csl_styles.style_for(None).label(source, 0)


def reference_line(source: CitedSource) -> str:
    return csl_styles.style_for(None).reference(source, 0)


def references(sections: list[Section], sources: dict[str, CitedSource], style: str | None = None) -> list[CitedSource]:
    """The verified sources cited anywhere in the manuscript. Author-date styles sort by label then title (unchanged
    since before M6.5); a numbered style (`app.csl_styles`, e.g. vancouver/ieee) keeps first-citation order instead,
    so its reference-list numbers match the in-text markers."""
    ids: dict[str, None] = {}
    for section in sections:
        for source_id in cited_source_ids(section.content):
            ids.setdefault(source_id, None)
    cited = [sources[i] for i in ids if i in sources and sources[i].verified]
    cslstyle = csl_styles.style_for(style)
    if cslstyle.numbered:
        return cited
    return sorted(cited, key=lambda s: (cslstyle.label(s, 0).lower(), s.title.lower()))


def _citation_labels(cslstyle: csl_styles.CslStyle, sections: list[Section], sources: dict[str, CitedSource]) -> dict[str, str]:
    """source id -> in-text marker for every verified, known cited source, under the given style."""
    if cslstyle.numbered:
        ordered = references(sections, sources, cslstyle.id)
        return {s.id: cslstyle.label(s, i) for i, s in enumerate(ordered, start=1)}
    return {sid: cslstyle.label(src, 0) for sid, src in sources.items() if src.verified}


def _reference_lines(cslstyle: csl_styles.CslStyle, refs: list[CitedSource]) -> list[str]:
    return [cslstyle.reference(s, i) for i, s in enumerate(refs, start=1)]


def _statement_text(value: str | None, label: str) -> str:
    text = " ".join((value or "").split())
    return text or STATEMENT_FILL.format(label)


def _credit_lines(credit: tuple[tuple[str, tuple[str, ...]], ...]) -> list[str]:
    """One line per contributor who has at least one role; a member with no roles yet is left out (nothing
    to say about them), not shown with an empty role list."""
    return [f"{name}: {', '.join(roles)}" for name, roles in credit if roles]


def to_markdown(
    title: str,
    sections: list[Section],
    sources: dict[str, CitedSource],
    runs: dict[str, Any] | None = None,
    *,
    style: str | None = None,
    statements: Statements | None = None,
) -> str:
    cslstyle = csl_styles.style_for(style)
    labels = _citation_labels(cslstyle, sections, sources)
    out: list[str] = [f"# {title}", ""]
    for section in sections:
        out += [f"## {section.title}", ""]
        out += _markdown_blocks(section.content.get("content") or [], sources, runs or {}, labels, indent="", heading_offset=1)
    refs = references(sections, sources, style)
    if refs:
        out += [f"## {REFERENCES_TITLE}", ""]
        out += [f"- {line}" for line in _reference_lines(cslstyle, refs)] + [""]
    if statements is not None:
        out += [f"## {STATEMENTS_TITLE}", ""]
        for field, label in STATEMENT_FIELDS:
            out += [f"### {label}", "", _statement_text(getattr(statements, field), label), ""]
        out += [f"## {CREDIT_TITLE}", ""]
        lines = _credit_lines(statements.credit)
        out += [f"- {line}" for line in lines] + [""] if lines else [NO_CONTRIBUTORS, ""]
    return "\n".join(out).rstrip("\n") + "\n"


def to_docx(
    title: str,
    sections: list[Section],
    sources: dict[str, CitedSource],
    runs: dict[str, Any] | None = None,
    *,
    style: str | None = None,
    statements: Statements | None = None,
) -> bytes:
    cslstyle = csl_styles.style_for(style)
    labels = _citation_labels(cslstyle, sections, sources)
    word = WordDocument()
    word.core_properties.title = title
    word.add_heading(title, level=0)
    for section in sections:
        word.add_heading(section.title, level=1)
        _docx_blocks(word, section.content.get("content") or [], sources, runs or {}, labels, list_style=None, depth=0, heading_offset=1)
    refs = references(sections, sources, style)
    if refs:
        word.add_heading(REFERENCES_TITLE, level=1)
        for line in _reference_lines(cslstyle, refs):
            word.add_paragraph(line, style="List Bullet")
    if statements is not None:
        word.add_heading(STATEMENTS_TITLE, level=1)
        for field, label in STATEMENT_FIELDS:
            word.add_heading(label, level=2)
            word.add_paragraph(_statement_text(getattr(statements, field), label))
        word.add_heading(CREDIT_TITLE, level=1)
        lines = _credit_lines(statements.credit)
        if lines:
            for line in lines:
                word.add_paragraph(line, style="List Bullet")
        else:
            word.add_paragraph(NO_CONTRIBUTORS)
    buffer = io.BytesIO()
    word.save(buffer)
    return buffer.getvalue()


def to_latex(
    title: str,
    sections: list[Section],
    sources: dict[str, CitedSource],
    runs: dict[str, Any] | None = None,
    *,
    style: str | None = None,
    statements: Statements | None = None,
) -> str:
    """A self-contained `article`-class document. References and statements render as plain text (no `\\cite`/BibTeX
    keys — the same plain-text approach `to_markdown`/`to_docx` use, so all three export formats agree on content)."""
    cslstyle = csl_styles.style_for(style)
    labels = _citation_labels(cslstyle, sections, sources)
    out: list[str] = [
        r"\documentclass{article}",
        r"\usepackage[utf8]{inputenc}",
        r"\usepackage{hyperref}",
        f"\\title{{{_latex_escape(title)}}}",
        r"\date{}",
        r"\begin{document}",
        r"\maketitle",
        "",
    ]
    for section in sections:
        out += [f"\\section{{{_latex_escape(section.title)}}}", ""]
        out += _latex_blocks(section.content.get("content") or [], sources, runs or {}, labels, heading_offset=1)
    refs = references(sections, sources, style)
    if refs:
        out += [f"\\section*{{{_latex_escape(REFERENCES_TITLE)}}}", r"\begin{itemize}"]
        out += [f"\\item {_latex_escape(line)}" for line in _reference_lines(cslstyle, refs)]
        out += [r"\end{itemize}", ""]
    if statements is not None:
        out += [f"\\section*{{{_latex_escape(STATEMENTS_TITLE)}}}"]
        for field, label in STATEMENT_FIELDS:
            out += [f"\\subsection*{{{_latex_escape(label)}}}", _latex_escape(_statement_text(getattr(statements, field), label)), ""]
        out += [f"\\section*{{{_latex_escape(CREDIT_TITLE)}}}"]
        lines = _credit_lines(statements.credit)
        if lines:
            out += [r"\begin{itemize}"] + [f"\\item {_latex_escape(line)}" for line in lines] + [r"\end{itemize}", ""]
        else:
            out += [_latex_escape(NO_CONTRIBUTORS), ""]
    out += [r"\end{document}", ""]
    return "\n".join(out).rstrip("\n") + "\n"


def to_json(
    title: str,
    sections: list[dict[str, Any]],
    sources: list[CitedSource],
    *,
    statements: Statements | None = None,
) -> dict[str, Any]:
    """`sections` are already shaped by the caller (id, title, version, content_json, content_text). References are
    plain fields here (no style formatting — a JSON consumer formats its own citations)."""
    body: dict[str, Any] = {
        "title": title,
        "sections": sections,
        "references": [
            {"id": s.id, "title": s.title, "authors": list(s.authors), "year": s.year, "venue": s.venue, "doi": s.doi}
            for s in sources
        ],
    }
    if statements is not None:
        body["statements"] = {
            "data_availability": statements.data_availability,
            "conflict_of_interest": statements.conflict_of_interest,
            "ethics": statements.ethics,
            "ai_use_disclosure": statements.ai_use_disclosure,
        }
        body["credit"] = [{"name": name, "roles": list(roles)} for name, roles in statements.credit]
    return body


# ---------------------------------------------------------------- helpers


def _walk(node: dict[str, Any]) -> Iterator[dict[str, Any]]:
    yield node
    for child in node.get("content") or []:
        yield from _walk(child)


def _text_marks(node: dict[str, Any]) -> tuple[bool, bool]:
    names = {m.get("type") for m in node.get("marks") or []}
    return "strong" in names, "em" in names


def _stat_text(node: dict[str, Any], runs: dict[str, Any]) -> str:
    attrs = node.get("attrs") or {}
    run_id, path = attrs.get("analysis_run_id", ""), attrs.get("path", "")
    if run_id not in runs:
        return UNVERIFIED_NUMBER_LABEL
    value = number_citation.resolve_number(runs[run_id], path)
    return UNVERIFIED_NUMBER_LABEL if value is None else json.dumps(value)


def _inline_text(node: dict[str, Any], sources: dict[str, CitedSource], runs: dict[str, Any], labels: dict[str, str]) -> str:
    kind = node.get("type")
    if kind == "text":
        return node.get("text", "")
    if kind == "cite":
        source_id = (node.get("attrs") or {}).get("source_id", "")
        source = sources.get(source_id)
        if source is None:
            return UNKNOWN_LABEL
        if not source.verified:
            return UNVERIFIED_LABEL
        return labels.get(source_id, UNKNOWN_LABEL)
    if kind == "stat":
        return _stat_text(node, runs)
    if kind == "hard_break":
        return "\n"
    return ""


def _markdown_inline(nodes: list[dict[str, Any]], sources: dict[str, CitedSource], runs: dict[str, Any], labels: dict[str, str]) -> str:
    text = ""
    for node in nodes:
        piece = _inline_text(node, sources, runs, labels)
        if node.get("type") == "hard_break":
            text += "  \n"
            continue
        strong, em = _text_marks(node)
        core = piece.strip()
        if core and strong:
            core = f"**{core}**"
        if core and em:
            core = f"*{core}*"
        # Spaces stay outside the markers: "* word *" is not emphasis in Markdown.
        text += piece[: len(piece) - len(piece.lstrip())] + core + piece[len(piece.rstrip()):] if piece.strip() else piece
    return text


def _markdown_blocks(
    blocks: list[dict[str, Any]], sources: dict[str, CitedSource], runs: dict[str, Any], labels: dict[str, str], *, indent: str, heading_offset: int
) -> list[str]:
    out: list[str] = []
    for block in blocks:
        kind = block.get("type")
        children = block.get("content") or []
        if kind == "paragraph":
            out += [indent + _markdown_inline(children, sources, runs, labels), ""]
        elif kind == "heading":
            level = min(int((block.get("attrs") or {}).get("level", 2)) + heading_offset, 6)
            out += [f"{'#' * level} {_markdown_inline(children, sources, runs, labels)}", ""]
        elif kind == "blockquote":
            inner = _markdown_blocks(children, sources, runs, labels, indent="", heading_offset=heading_offset)
            out += [f"> {line}" if line else ">" for line in inner]
        elif kind in ("bullet_list", "ordered_list"):
            for number, item in enumerate(children, start=1):
                marker = "-" if kind == "bullet_list" else f"{number}."
                inner = _markdown_blocks(
                    item.get("content") or [], sources, runs, labels, indent=indent + " " * (len(marker) + 1), heading_offset=heading_offset
                )
                if inner:
                    inner[0] = indent + marker + " " + inner[0].lstrip()
                out += [line for line in inner if line != ""]
            out.append("")
    return out


def _docx_inline(paragraph: Paragraph, nodes: list[dict[str, Any]], sources: dict[str, CitedSource], runs: dict[str, Any], labels: dict[str, str]) -> None:
    for node in nodes:
        if node.get("type") == "hard_break":
            paragraph.add_run().add_break()
            continue
        text = _inline_text(node, sources, runs, labels)
        if not text:
            continue
        run = paragraph.add_run(text)
        strong, em = _text_marks(node)
        run.bold = strong or None
        run.italic = em or None


def _docx_blocks(
    word: Any,
    blocks: list[dict[str, Any]],
    sources: dict[str, CitedSource],
    runs: dict[str, Any],
    labels: dict[str, str],
    *,
    list_style: str | None,
    depth: int,
    heading_offset: int,
) -> None:
    for block in blocks:
        kind = block.get("type")
        children = block.get("content") or []
        if kind == "paragraph":
            style = list_style
            if style and depth > 1:
                style = f"{style} {min(depth, 3)}"
            paragraph = word.add_paragraph(style=style)
            _docx_inline(paragraph, children, sources, runs, labels)
        elif kind == "heading":
            level = min(int((block.get("attrs") or {}).get("level", 2)) + heading_offset - 1, 9)
            paragraph = word.add_heading(level=level)
            _docx_inline(paragraph, children, sources, runs, labels)
        elif kind == "blockquote":
            for child in children:
                if child.get("type") == "paragraph":
                    _docx_inline(word.add_paragraph(style="Quote"), child.get("content") or [], sources, runs, labels)
                else:
                    _docx_blocks(word, [child], sources, runs, labels, list_style=list_style, depth=depth, heading_offset=heading_offset)
        elif kind in ("bullet_list", "ordered_list"):
            style = "List Bullet" if kind == "bullet_list" else "List Number"
            for item in children:
                _docx_blocks(word, item.get("content") or [], sources, runs, labels, list_style=style, depth=depth + 1, heading_offset=heading_offset)


# ---------------------------------------------------------------- LaTeX helpers

_LATEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def _latex_escape(text: str) -> str:
    return "".join(_LATEX_SPECIALS.get(ch, ch) for ch in text)


def _latex_inline(nodes: list[dict[str, Any]], sources: dict[str, CitedSource], runs: dict[str, Any], labels: dict[str, str]) -> str:
    text = ""
    for node in nodes:
        if node.get("type") == "hard_break":
            text += "\\\\\n"
            continue
        piece = _latex_escape(_inline_text(node, sources, runs, labels))
        strong, em = _text_marks(node)
        core = piece.strip()
        if core and strong:
            core = f"\\textbf{{{core}}}"
        if core and em:
            core = f"\\textit{{{core}}}"
        text += piece[: len(piece) - len(piece.lstrip())] + core + piece[len(piece.rstrip()):] if piece.strip() else piece
    return text


def _latex_heading(level: int, text: str) -> str:
    commands = ["section", "subsection", "subsubsection", "paragraph", "subparagraph"]
    command = commands[min(max(level - 1, 0), len(commands) - 1)]
    return f"\\{command}{{{text}}}"


def _latex_blocks(blocks: list[dict[str, Any]], sources: dict[str, CitedSource], runs: dict[str, Any], labels: dict[str, str], *, heading_offset: int) -> list[str]:
    out: list[str] = []
    for block in blocks:
        kind = block.get("type")
        children = block.get("content") or []
        if kind == "paragraph":
            out += [_latex_inline(children, sources, runs, labels), ""]
        elif kind == "heading":
            level = int((block.get("attrs") or {}).get("level", 2)) + heading_offset
            out += [_latex_heading(level, _latex_inline(children, sources, runs, labels)), ""]
        elif kind == "blockquote":
            inner = _latex_blocks(children, sources, runs, labels, heading_offset=heading_offset)
            out += [r"\begin{quote}"] + inner + [r"\end{quote}", ""]
        elif kind in ("bullet_list", "ordered_list"):
            env = "itemize" if kind == "bullet_list" else "enumerate"
            out += [f"\\begin{{{env}}}"]
            for item in children:
                inner = _latex_blocks(item.get("content") or [], sources, runs, labels, heading_offset=heading_offset)
                inner = [line for line in inner if line != ""]
                if inner:
                    out += [f"\\item {inner[0]}"] + inner[1:]
            out += [f"\\end{{{env}}}", ""]
    return out
